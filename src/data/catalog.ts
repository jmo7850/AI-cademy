const CLAUDE_ACADEMY = 'https://academy.claude.com/all';

function claudeCourse(
  slug: string,
  title: string,
  hours: number,
  lessons: number,
  extra: Partial<CatalogEntry> & Pick<CatalogEntry, 'objectives' | 'difficulty'>,
): CatalogEntry {
  const url = `https://academy.claude.com/courses/${slug}`;
  return {
    id: `claude-${slug}`,
    title,
    provider: 'anthropic',
    track: 'A',
    category: 'ai',
    credentialType: 'course-certificate',
    prerequisites: [],
    studyHours: verified(hours, `Stated on the catalog listing (${lessons} lessons).`),
    learningCost: unverified('free', 'Claude Academy describes its catalog as free courses; per-course price is not shown.'),
    credentialFree: unverified(true, 'A completion badge is shown on some course pages; not confirmed for every course.'),
    officialUrl: url,
    registrationUrl: url,
    sourceUrl: CLAUDE_ACADEMY,
    checkedOn: D,
    availability: verified('available'),
    proves: 'You completed a provider course and its quiz. It is a course completion badge, not an industry certification.',
    programmingRequired: false,
    handsOn: false,
    careerValue: 'Shows practical familiarity with Claude. Pair it with a project to show you can apply it.',
    nextSteps: [],
    origin: 'official',
    ...extra,
  };
}

